func newContainerToolsCmd(a *app) *cobra.Command {
	return &cobra.Command{
		Use:   "tools",
		Short: "List the tools a generated container can install",
		Args:  noArgs(),
		RunE: func(cmd *cobra.Command, args []string) error {
			return runContainerTools(a)
		},
	}
}

func runContainerTools(a *app) error {
	return a.table(func(w io.Writer) {
		header(w, "TOOL", "SUMMARY", "SOURCE")
		for _, t := range dcgen.Catalog() {
			source := "community"
			if t.Official {
				source = "official"
			}
			row(w, t.ID, t.Summary, source)
		}
	})
}

func newContainerConfigCmd(a *app) *cobra.Command {
	cmd := &cobra.Command{
		Use:   "config",
		Short: "Inspect the configuration a container is built from",
		Args:  noArgs(),
		RunE:  groupRunE,
	}

	var workspace string
	show := &cobra.Command{
		Use:   "show NAME",
		Short: "Print the record and devcontainer config a container is built from",
		Args:  exactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			return runContainerConfigShow(cmd.Context(), a, workspace, args[0])
		},
	}
	addWorkspaceFlag(show, &workspace)

	cmd.AddCommand(show)
	return cmd
}

func runContainerConfigShow(ctx context.Context, a *app, workspace, name string) error {
	t, err := a.resolve(ctx, workspace, name)
	if err != nil {
		return err
	}
	defer t.release()

	// The record first, on stderr: the document alone leaves out what the row
	// knows — mode, the state volume setting, the host access grant — and
	// stdout must stay the document alone so `config show | jq` still works.
	printContainerRecord(a, t.container)

	if t.container.GeneratedConfig != "" {
		a.printf("%s", t.container.GeneratedConfig)
		return nil
	}

	// A project-owned container: the file on disk is not the whole answer,
	// since dev merges its state mount in per invocation. Printing only the
	// path would name a file that is not quite what ran.
	//
	// Fatal on a parse error, unlike stop or remove, since this must not show a
	// file dev could not use.
	if err := t.requireOverride(a); err != nil {
		return err
	}

	if t.container.OverrideConfigPath == "" {
		// Without state there is no merge, so the project's file is what the
		// CLI gets.
		return printFile(a, t.container.ConfigPath)
	}
	return printFile(a, t.container.OverrideConfigPath)
}

// printContainerRecord writes what dev recorded about a container: the columns
// `container list` prints, and the settings that have no column there. Stderr,
// so a pipe receives the document and nothing else.
func printContainerRecord(a *app, c model.Container) {
	tw := tabwriter.NewWriter(a.stderr(), 0, 0, 2, ' ', 0)
	defer func() { _ = tw.Flush() }()
	kv := func(key, value string) { fmt.Fprintf(tw, "  %s:\t%s\n", key, value) }

	fmt.Fprintf(tw, "container %s (workspace %s)\n", c.Name, c.WorkspaceName)
	if c.SourceKind == model.SourceNone {
		kv("source", "no folder; its work lives in a volume dev owns")
	} else {
		kv("source", xpath.Shorten(c.Source))
	}
	for _, f := range c.Folders {
		kv("folder", fmt.Sprintf("%s -> %s", xpath.Shorten(f.HostPath), f.ContainerPath))
	}
	kv("config", configProvenance(c))
	kv("mode", displayMode(c.Mode))
	if c.Mode == model.ModeLegacy {
		// Meaningful for these only; newer modes carry the answer in mode.
		kv("git guard", onOff(c.GitGuard))
	}
	kv("state", onOff(c.PersistState))
	kv("host access", hostAccessOf(c))
	kv("agents", agentConfigSummary(c))
	if c.WorktreeRepo != "" {
		kv("worktree of", xpath.Shorten(c.WorktreeRepo))
	}
	if c.WorkspacePath != "" {
		kv("volume at", c.WorkspacePath)
	}
	kv("created", c.CreatedAt.Local().Format("2006-01-02 15:04:05"))
}

// configProvenance says where the document on stdout came from: dev's own
// rendering, or the project's file, merged with the state mount or not.
func configProvenance(c model.Container) string {
	if c.GeneratedConfig != "" {
		return "generated by dev"
	}
	source := xpath.Shorten(c.ConfigPath)
	if c.OverrideConfigPath == "" {
		return source + " (no merge: state off)"
	}
	return "merged from " + source
}

// agentConfigSummary is the agents.yaml a container applies: the project's, one
// named at create, or none. Pending means it is still owed inside the
// container; invalid means start and rebuild would refuse it as it stands.
func agentConfigSummary(c model.Container) string {
	if c.AgentConfig == agentConfigNone {
		return "none"
	}
	file, err := agentConfigFile(c)
	switch {
	case err != nil && exitCodeOf(err) == exitNotFound:
		// Named at create and gone since: a rebuild refuses, but printing the
		// document must not. Say what is wrong here instead of failing.
		return xpath.Shorten(c.AgentConfig) + ", missing"
	case err != nil:
		return xpath.Shorten(c.AgentConfig) + ", unreadable"
	case file == "":
		return "none"
	}
	s := "project (.devcontainer/agents.yaml)"
	if c.AgentConfig != "" {
		s = xpath.Shorten(file)
	}
	if _, err := agentcfg.Load(file); err != nil {
		// Usually the project edited it after create; the first command that
		// needs it reports why.
		s += ", invalid"
	}
	if c.AgentConfigPending {
		s += ", not yet applied"
	}
	return s
}

// printFile copies a configuration document to stdout. Warnings go to stderr,
// so `config show | jq` still gets valid JSON.
func printFile(a *app, path string) error {
	body, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("reading %s: %w", path, err)
	}
	a.printf("%s", body)
	return nil
}
